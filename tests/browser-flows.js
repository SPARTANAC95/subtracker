// Run with playwright-cli run-code --filename=tests/browser-flows.js.
// Only an isolated review server is accepted; never touches the user's data/.
async page => {
  const base = page.url().split('/').slice(0, 3).join('/')
  const server = await (await page.request.get(`${base}/api/status`)).json()
  if (!server.dataFile.includes('subtracker-review')) throw new Error('Use an isolated SUBTRACKER_DATA_DIR containing subtracker-review')
  const context = await page.context().browser().newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Europe/Warsaw', reducedMotion: 'reduce', serviceWorkers: 'block' })
  const app = await context.newPage()
  app.setDefaultTimeout(8000)
  try {
  const errors = []
  app.on('pageerror', error => errors.push(error.message))
  app.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const assert = (value, message) => { if (!value) throw new Error(message) }
  const read = () => app.evaluate(() => JSON.parse(localStorage.getItem('st-subs') || '[]'))
  const waitSub = (name, predicate) => app.waitForFunction(({ name, expression }) => {
    const sub = JSON.parse(localStorage.getItem('st-subs') || '[]').find(s => s.name === name)
    return sub && new Function('s', `return ${expression}`)(sub)
  }, { name, expression: predicate })
  const close = async () => { await app.keyboard.press('Escape'); await app.waitForFunction(() => !document.querySelector('[role="dialog"]')) }
  const nav = async name => {
    await app.getByRole('navigation', { name: 'Primary navigation', exact: true }).getByRole('button', { name }).click()
    await app.waitForTimeout(600) // allow the exiting and entering view to finish
  }
  await page.request.delete(`${base}/api/data`)
  await app.goto(base)
  await app.getByRole('button', { name: 'Next', exact: true }).click()
  await app.getByRole('button', { name: '$ USD', exact: true }).click()
  await app.getByRole('button', { name: 'Next', exact: true }).click()
  await app.getByRole('spinbutton', { name: 'Monthly budget' }).fill('120')
  await app.getByRole('button', { name: 'Get started' }).click()
  await app.getByRole('button', { name: 'Add your first subscription' }).click()
  let dialog = app.getByRole('dialog')
  await dialog.getByRole('textbox', { name: 'Service name' }).fill('Review Plan')
  await dialog.getByRole('spinbutton', { name: 'Amount ($)' }).fill('20')
  await dialog.getByRole('button', { name: 'Add subscription', exact: true }).click()
  await waitSub('Review Plan', 's.amount === 20')
  await app.getByRole('button', { name: 'Paid', exact: true }).click()
  await waitSub('Review Plan', 's.paymentHistory.length === 1')
  await app.getByRole('button', { name: 'Undo', exact: true }).click()
  await waitSub('Review Plan', 's.paymentHistory.length === 0')
  await app.getByRole('button', { name: 'Paid', exact: true }).click()
  await waitSub('Review Plan', 's.paymentHistory[0].currency === "USD"')
  await nav(/^Subscriptions/)
  await app.getByRole('button', { name: 'Review Plan Other', exact: true }).click()
  await app.getByRole('dialog').getByRole('button', { name: 'Edit', exact: true }).click()
  dialog = app.getByRole('dialog', { name: 'Edit subscription' })
  await dialog.getByRole('combobox', { name: 'Currency', exact: true }).selectOption('EUR')
  await dialog.getByRole('textbox', { name: 'URL', exact: true }).fill('javascript:alert(1)')
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  assert(await dialog.getByRole('alert').isVisible(), 'Unsafe URL has no form error')
  await dialog.getByRole('textbox', { name: 'URL', exact: true }).fill('example.com/account')
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await waitSub('Review Plan', 's.currency === "EUR" && s.paymentHistory[0].currency === "USD" && s.url === "https://example.com/account"')
  await app.getByRole('dialog').waitFor({ state: 'hidden' })
  assert(await app.evaluate(() => document.body.style.overflow !== 'hidden'), 'Scroll remains locked after detail to edit transition')
  await app.getByRole('button', { name: 'Review Plan Other', exact: true }).click()
  dialog = app.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Pause', exact: true }).click()
  await waitSub('Review Plan', 's.status === "paused"')
  await dialog.getByRole('button', { name: 'Resume', exact: true }).click()
  await waitSub('Review Plan', 's.status === "active"')
  await dialog.getByRole('button', { name: 'Archive as canceled', exact: true }).click()
  await app.getByRole('alertdialog').getByRole('button', { name: 'Archive', exact: true }).click()
  await waitSub('Review Plan', 's.status === "canceled"')
  await app.getByRole('button', { name: /^Canceled \(/ }).click()
  await app.getByRole('button', { name: 'Review Plan Other', exact: true }).click()
  await app.getByRole('dialog').getByRole('button', { name: 'Reactivate', exact: true }).click()
  await waitSub('Review Plan', 's.status === "active" && s.paymentHistory.length === 1')
  await close()
  await nav(/^Reminders/)
  await app.getByRole('button', { name: 'Add your first reminder' }).click()
  dialog = app.getByRole('dialog')
  await dialog.getByRole('textbox', { name: 'Service name' }).fill('Annual License')
  await dialog.getByRole('spinbutton', { name: 'Price paid ($)' }).fill('80')
  const tomorrow = await app.evaluate(() => { const d = new Date(); d.setDate(d.getDate() + 1); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}` })
  await dialog.getByLabel('Ends on', { exact: true }).fill(tomorrow)
  await dialog.getByRole('button', { name: 'Add reminder', exact: true }).click()
  await waitSub('Annual License', 's.kind === "reminder"')
  await nav('Overview')
  for (const dismiss of await app.getByRole('button', { name: 'Dismiss', exact: true }).all()) await dismiss.click()
  await app.waitForTimeout(250)
  await app.screenshot({ path: 'output/playwright/after-desktop.png', fullPage: true })
  await nav('Calendar')
  await app.getByRole('heading', { name: /September|October|November|December|January|February|March|April|May|June|July|August/ }).first().waitFor()
  await app.screenshot({ path: 'output/playwright/after-calendar.png', fullPage: true })
  await nav('Insights')
  await app.getByRole('heading', { name: 'Monthly spend — six months & forecast', exact: true }).waitFor()
  await nav('Settings')
  await app.getByRole('combobox', { name: 'Currency', exact: true }).selectOption('GBP')
  await app.waitForFunction(() => JSON.parse(localStorage.getItem('st-settings')).currency === 'GBP')
  assert((await read()).find(s => s.name === 'Annual License').currency === 'USD', 'Changing display currency repriced reminder')
  const downloadEvent = app.waitForEvent('download')
  await app.getByRole('button', { name: 'Backup', exact: true }).click()
  const download = await downloadEvent
  await download.saveAs('output/playwright/exported-backup.json')
  await app.getByRole('button', { name: 'Save now', exact: true }).click()
  await app.getByText('Saved to your data file', { exact: true }).waitFor()
  const disk = await (await app.request.get(`${base}/api/data`)).json()
  assert(disk.subs.length === 2 && disk.settings.currency === 'GBP', 'Disk snapshot differs from UI')
  await app.getByRole('spinbutton', { name: 'Monthly budget' }).fill('999')
  const fileEvent = app.waitForEvent('filechooser')
  await app.getByRole('button', { name: 'Restore backup…', exact: true }).click()
  await (await fileEvent).setFiles('output/playwright/exported-backup.json')
  await app.getByRole('alertdialog').getByRole('button', { name: 'Confirm', exact: true }).click()
  await app.waitForFunction(() => JSON.parse(localStorage.getItem('st-settings')).budget === 120)
  await app.reload()
  await app.getByRole('navigation', { name: 'Primary navigation', exact: true }).waitFor()
  assert((await read()).length === 2, 'Reload lost records')
  await app.setViewportSize({ width: 390, height: 844 })
  await app.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('button', { name: 'Subscriptions', exact: true }).click()
  await app.getByRole('button', { name: /^Active \(/ }).click()
  const row = app.locator('article').filter({ hasText: 'Review Plan' })
  await row.waitFor()
  assert((await row.boundingBox()).y < 650, 'Mobile filters push all records below the viewport')
  await app.getByRole('button', { name: /Filters & sort/ }).click()
  await app.getByRole('combobox', { name: 'Category', exact: true }).selectOption('other')
  await app.getByRole('button', { name: /Hide filters/ }).click()
  await app.screenshot({ path: 'output/playwright/after-mobile.png', fullPage: true })
  await app.getByRole('button', { name: 'Search subscriptions' }).click()
  await app.getByRole('combobox', { name: 'Command palette search' }).fill('Review Plan')
  await app.keyboard.press('Enter')
  await app.getByRole('dialog').getByRole('heading', { name: 'Review Plan' }).waitFor()
  await close()
  await app.getByRole('button', { name: 'Open Settings' }).click()
  await app.getByText('Your data on this PC', { exact: true }).waitFor()
  await app.screenshot({ path: 'output/playwright/after-mobile-settings.png', fullPage: true })
  for (const width of [320, 390, 768, 1440]) {
    await app.setViewportSize({ width, height: 900 })
    assert(await app.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Horizontal overflow at ${width}px`)
  }
  assert(errors.length === 0, `Runtime errors: ${errors.join('; ')}`)
  return { passed: ['setup', 'add', 'payment and undo', 'edit validation', 'payment currency', 'pause and resume', 'archive and reactivate', 'reminders', 'calendar', 'insights', 'settings', 'export and full restore', 'disk persistence', 'reload', 'mobile filters', 'palette', 'responsive widths'], runtimeErrors: errors }
  } finally { await context.close() }
}
